#!/usr/bin/env python3
"""Build the data bundle the web viewer loads.

The virtual repo is real code. This script runs its pipeline twice:

  1. in a temp copy with virtual-repo/head-overrides/ applied  -> the "HEAD" commit
  2. in virtual-repo/working/ itself                           -> the working tree

It then compares the two trees the way `git status` would and writes
public/repo-data.js (text files, statuses, terminal transcript) plus
public/repo-assets/ (images for both sides of the diff).

Usage:  python tools/build.py        (needs pandas + seaborn, see README)
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VREPO = ROOT / "virtual-repo"
WORKING = VREPO / "working"
OVERRIDES = VREPO / "head-overrides"
PUBLIC = ROOT / "public"
ASSETS = PUBLIC / "repo-assets"
IMAGE_TYPES = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp"}
SKIP = {"__pycache__", ".DS_Store"}


def run_pipeline(tree: Path, commands: list[str], generated: list[str]) -> list[dict]:
    """Delete generated folders, then run each command from the tree's root."""
    for folder in generated:
        shutil.rmtree(tree / folder, ignore_errors=True)
    transcript = []
    for command in commands:
        argv = command.split()
        if argv[0] == "python":
            argv[0] = sys.executable
        result = subprocess.run(
            argv, cwd=tree, capture_output=True, text=True,
            env={"PATH": "/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1",
                 "MPLCONFIGDIR": tempfile.gettempdir()},
        )
        if result.returncode != 0:
            sys.exit(f"FAILED in {tree}: {command}\n{result.stdout}{result.stderr}")
        transcript.append({"command": command, "output": result.stdout.rstrip("\n")})
    return transcript


def read_tree(tree: Path) -> dict[str, Path]:
    return {
        p.relative_to(tree).as_posix(): p
        for p in sorted(tree.rglob("*"))
        if p.is_file() and not SKIP.intersection(p.parts)
    }


def main() -> None:
    meta = json.loads((VREPO / "meta.json").read_text())

    with tempfile.TemporaryDirectory() as tmp:
        head = Path(tmp) / "head"
        ignore = shutil.ignore_patterns(*SKIP)
        shutil.copytree(WORKING, head, ignore=ignore)
        shutil.copytree(OVERRIDES, head, ignore=ignore, dirs_exist_ok=True)
        run_pipeline(head, meta["pipeline"], meta["generated"])
        terminal = run_pipeline(WORKING, meta["pipeline"], meta["generated"])

        head_files, work_files = read_tree(head), read_tree(WORKING)
        shutil.rmtree(ASSETS, ignore_errors=True)
        files = []
        for path in sorted(set(head_files) | set(work_files)):
            old, new = head_files.get(path), work_files.get(path)
            if old and new:
                status = "" if old.read_bytes() == new.read_bytes() else "M"
            else:
                status = "U" if new else "D"
            entry = {"path": path, "status": status}
            is_image = Path(path).suffix.lower() in IMAGE_TYPES
            entry["kind"] = "image" if is_image else "text"
            for side, src in (("working", new), ("head", old)):
                if src is None or (side == "head" and not status):
                    continue
                if is_image:
                    dest = ASSETS / side / path
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(src, dest)
                    entry[side] = f"repo-assets/{side}/{path}"
                else:
                    entry[side] = src.read_text(encoding="utf-8")
            files.append(entry)

    bundle = {
        "name": meta["name"],
        "branch": meta["branch"],
        "commitMessage": meta["commitMessage"],
        "files": files,
        "terminal": terminal,
    }
    PUBLIC.mkdir(exist_ok=True)
    out = PUBLIC / "repo-data.js"
    out.write_text(
        "// Generated by tools/build.py. Do not edit by hand.\n"
        f"window.REPO_DATA = {json.dumps(bundle, indent=1)};\n",
        encoding="utf-8",
    )

    changed = [f for f in files if f["status"]]
    print(f"{len(files)} files, {len(changed)} changed -> {out.relative_to(ROOT)}")
    for f in changed:
        print(f"  {f['status']}  {f['path']}")


if __name__ == "__main__":
    main()
